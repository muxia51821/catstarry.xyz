import { readFile, rm } from 'node:fs/promises';

const [expectedPath, generatedPath] = process.argv.slice(2);
if (!expectedPath || !generatedPath) {
  throw new Error('Expected generated and checked Worker type paths.');
}

function normalize(source) {
  return source
    .replace(/^[ \t]*\/\/ Generated by Wrangler by running `wrangler types .*` \(hash: ([a-f0-9]+)\)\r?$/m, '// Generated by Wrangler (hash: $1)')
    .replace(/[ \t]+(?=\r?$)/gm, '');
}

try {
  const [expected, generated] = await Promise.all([
    readFile(expectedPath, 'utf8'),
    readFile(generatedPath, 'utf8'),
  ]);
  const normalizedExpected = normalize(expected);
  const normalizedGenerated = normalize(generated);
  if (normalizedExpected !== normalizedGenerated) {
    const expectedLines = normalizedExpected.split('\n');
    const generatedLines = normalizedGenerated.split('\n');
    const line = expectedLines.findIndex((value, index) => value !== generatedLines[index]) + 1;
    throw new Error(`${expectedPath} is out of date at normalized line ${line}. Run npm run worker:types.`);
  }
} finally {
  await rm(generatedPath, { force: true });
}
