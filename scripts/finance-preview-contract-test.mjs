import assert from 'node:assert/strict';
import { once } from 'node:events';
import { startFinancePreview } from './finance-preview.mjs';

const server = startFinancePreview(0);
await once(server, 'listening');
const address = server.address();
if (!address || typeof address === 'string') throw new Error('Finance preview did not expose a TCP port');
const baseUrl = `http://127.0.0.1:${address.port}`;

try {
  const page = await fetch(`${baseUrl}/`);
  assert.equal(page.status, 200);
  assert.match(await page.text(), /数据面板/);
  const session = await fetch(`${baseUrl}/api/auth/session`).then((response) => response.json());
  assert.equal(session.authenticated, false);
  const login = await fetch(`${baseUrl}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'preview-admin', password: 'local-only' }) }).then((response) => response.json());
  assert.deepEqual(login, { authenticated: true, username: 'local-admin', role: 'admin' });
  const holdings = await fetch(`${baseUrl}/api/holdings`).then((response) => response.json());
  assert.equal(holdings.total_market_value, 12600);
  const pe = await fetch(`${baseUrl}/api/pe`).then((response) => response.json());
  assert.equal(pe.indexes.find((row) => row.ticker === 'CSI300_PE').historical_position.status, 'available');
  assert.equal(pe.indexes.find((row) => row.ticker === 'CSI500_PE').historical_position.reason, 'insufficient_history');
  const accountState = await fetch(`${baseUrl}/api/account-state`).then((response) => response.json());
  assert.equal(accountState.portfolio_roles.percentage_available, true);
  assert.equal(accountState.portfolio_roles.total_assets, 13600);
  assert.equal(accountState.portfolio_roles.composition.find((row) => row.role === '机动仓')?.target_ratio, .15);
  const cashFlows = await fetch(`${baseUrl}/api/cash-flows`);
  assert.equal(cashFlows.status, 200);
  assert.equal((await cashFlows.json()).cash_flows.length, 1);
  const assetSnapshots = await fetch(`${baseUrl}/api/assets/snapshots`);
  assert.equal(assetSnapshots.status, 200);
  assert.equal((await assetSnapshots.json()).snapshots.length, 2);
  const riskSignals = await fetch(`${baseUrl}/api/risk/signals`);
  assert.equal(riskSignals.status, 200);
  assert.equal((await riskSignals.json()).signals[0].level, 'yellow');
  const cashFlowPayload = { occurred_on: '2026-07-30', contributor: 'muxia', flow_type: 'bonus_investment', bonus_source_year: '2026', baseline_amount: '', confirmed_amount: '10000', manager_share_offset: '1000', note: '本地预览现金流' };
  assert.equal((await fetch(`${baseUrl}/api/cash-flows`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ...cashFlowPayload, flow_type: 'invalid' }) })).status, 400);
  const createdCashFlow = await fetch(`${baseUrl}/api/cash-flows`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(cashFlowPayload) });
  assert.equal(createdCashFlow.status, 201);
  const createdCashFlowBody = await createdCashFlow.json();
  assert.equal(createdCashFlowBody.cash_flow.net_amount, 9000);
  const updatedCashFlow = await fetch(`${baseUrl}/api/cash-flows/${createdCashFlowBody.cash_flow.id}`, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ...cashFlowPayload, confirmed_amount: '12000' }) });
  assert.equal(updatedCashFlow.status, 200);
  assert.equal((await updatedCashFlow.json()).cash_flow.net_amount, 11000);
  const deletedCashFlow = await fetch(`${baseUrl}/api/cash-flows/${createdCashFlowBody.cash_flow.id}`, { method: 'DELETE', headers: { 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(deletedCashFlow.status, 200);
  assert.equal((await fetch(`${baseUrl}/api/cash-flows`).then((response) => response.json())).cash_flows.length, 1);
  assert.equal((await fetch(`${baseUrl}/api/cash-flows/${createdCashFlowBody.cash_flow.id}`, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(cashFlowPayload) })).status, 404);
  const createdSnapshot = await fetch(`${baseUrl}/api/assets/snapshots`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ snapshot_at: '2026-07-30T15:00', source: 'manual', holdings_value: 13000, cash_value: 2000, is_complete: true, incomplete_reason: null }) });
  assert.equal(createdSnapshot.status, 201);
  assert.equal((await createdSnapshot.json()).total_value, 15000);
  assert.equal((await fetch(`${baseUrl}/api/assets/snapshots`).then((response) => response.json())).snapshots.length, 3);
  const incompleteSnapshot = await fetch(`${baseUrl}/api/assets/snapshots`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ snapshot_at: '2026-08-01T15:00', source: 'manual', holdings_value: 14000, cash_value: 1000, is_complete: false, incomplete_reason: '等待账户对账。' }) });
  assert.equal(incompleteSnapshot.status, 201);
  const assetSeries = await fetch(`${baseUrl}/api/assets/series?view=month`).then((response) => response.json());
  assert.equal(assetSeries.series.length, 2);
  assert.equal('records' in assetSeries, false);
  assert.equal('legacy_monthly_records' in assetSeries, false);
  assert.equal((await fetch(`${baseUrl}/api/assets/snapshots`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ snapshot_at: '2026-08-01T15:00', source: 'manual', holdings_value: 14000, cash_value: 1000, is_complete: false, incomplete_reason: '' }) })).status, 400);
  const created = await fetch(`${baseUrl}/api/trades`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ trade_date: '2026-07-30', ticker: '510500', direction: 'buy', quantity: 1, price: 5, position_category: 'A股宽基指数底仓' }) }).then((response) => response.json());
  assert.equal(created.trade.ticker, '510500');
  const trades = await fetch(`${baseUrl}/api/trades?ticker=510500`).then((response) => response.json());
  assert.equal(trades.items.length, 1);
  await fetch(`${baseUrl}/api/auth/logout`, { method: 'POST' });
  await fetch(`${baseUrl}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'preview-viewer', password: 'local-only' }) });
  assert.equal((await fetch(`${baseUrl}/api/cash-flows`)).status, 200);
  assert.equal((await fetch(`${baseUrl}/api/assets/snapshots`)).status, 200);
  assert.equal((await fetch(`${baseUrl}/api/risk/signals`)).status, 200);
  assert.equal((await fetch(`${baseUrl}/api/cash-flows`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(cashFlowPayload) })).status, 403);
  assert.equal((await fetch(`${baseUrl}/api/cash-flows/1`, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(cashFlowPayload) })).status, 403);
  assert.equal((await fetch(`${baseUrl}/api/cash-flows/1`, { method: 'DELETE', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
  assert.equal((await fetch(`${baseUrl}/api/assets/snapshots`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ snapshot_at: '2026-08-02T15:00', source: 'manual', holdings_value: 14000, cash_value: 1000, is_complete: true, incomplete_reason: null }) })).status, 403);
  console.log('Finance local preview contract passed.');
} finally {
  await new Promise((resolve) => server.close(resolve));
}
